// BIN-185 — coverage manifest refresh. Regenerates docs/recaps/covered-shows.json from Firestore
// truth so /recap's discovery step can skip already-covered shows by reading a committed file
// instead of issuing one Firestore read per candidate (the previous approach — cheap per call, but
// adds up to dozens of round trips per run for zero new information on shows we already know are done).
//
//   GOOGLE_APPLICATION_CREDENTIALS=/abs/path/recaps-writer.json \
//     node functions/scripts/recap-coverage-manifest.mjs
//
// Uses listDocuments() — lists document REFERENCES only (ids), no field reads, so this does not
// count as billed Firestore document reads. Filters to `{tmdbId}_index` ids (recapIndexDocId shape),
// then does one cheap get() per index doc (still far fewer than N per-candidate checks during
// discovery) to record boundary/season-only counts for a useful manifest.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { initializeApp, applicationDefault } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';

const OUT_PATH = resolve('docs/recaps/covered-shows.json');
const INDEX_ID_RE = /^(\d+)_index$/;

initializeApp({ credential: applicationDefault() });
const db = getFirestore();

async function main() {
  const refs = await db.collection('recaps').listDocuments();
  const indexRefs = refs.filter((ref) => INDEX_ID_RE.test(ref.id));

  console.log(`found ${indexRefs.length} index docs out of ${refs.length} total recaps/ doc refs`);

  const entries = [];
  for (const ref of indexRefs) {
    const snap = await ref.get();
    const data = snap.data() ?? {};
    const tmdbId = Number(INDEX_ID_RE.exec(ref.id)[1]);
    entries.push({
      tmdbId,
      boundaryCount: Array.isArray(data.boundaries) ? data.boundaries.length : 0,
      seasonOnlySeasons: Array.isArray(data.seasonOnlySeasons) ? data.seasonOnlySeasons : [],
    });
  }

  entries.sort((a, b) => a.tmdbId - b.tmdbId);

  writeFileSync(
    OUT_PATH,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        note: 'Machine-generated by functions/scripts/recap-coverage-manifest.mjs — do not hand-edit. Re-run the script to refresh. A tmdbId present here has at least one boundary or season-only doc; absence means unconfirmed, not necessarily uncovered — verify via recaps/{tmdbId}_index before trusting a negative.',
        shows: entries,
      },
      null,
      2
    )
  );

  console.log(`wrote ${entries.length} covered shows -> ${OUT_PATH}`);
}

main();
